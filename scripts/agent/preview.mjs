import { createHash, randomUUID } from 'node:crypto';
import { mkdir, readFile, realpath, writeFile } from 'node:fs/promises';
import { createServer, get } from 'node:http';
import { basename, dirname, join } from 'node:path';

const escape = (text) => String(text).replace(/[&<>"']/g, (char) => ({
  '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;',
})[char]);

async function readEvidence(directory, filename) {
  if (!filename || basename(filename) !== filename || !/^[\w.-]+$/.test(filename)) {
    throw new Error('Invalid evidence filename.');
  }
  const path = await realpath(join(directory, filename));
  if (dirname(path) !== directory) throw new Error('Evidence file is outside the attempt.');
  return readFile(path);
}

async function render(receipt, attemptPath) {
  const checks = await Promise.all(receipt.checks.map(async (check) => {
    const logName = check.evidence.find((name) => name === `${check.name}.log`);
    const log = logName ? (await readEvidence(attemptPath, logName)).toString('utf8') : '';
    return `<section><h2>${escape(check.name)}</h2>
<p><strong>${escape(check.status)}</strong> · ${escape(check.suite)}${check.tests == null ? '' : ` · ${escape(check.tests)} tests`}</p>
${check.reason ? `<p>${escape(check.reason)}</p>` : ''}
<ul>${(check.cases ?? []).map((name) => `<li>${escape(name)}</li>`).join('')}</ul>
${log ? `<details><summary>Runner log</summary><pre>${escape(log)}</pre></details>` : ''}
</section>`;
  }));
  let change = '';
  if (receipt.change_patch) {
    const patch = receipt.change_patch;
    const diff = await readEvidence(attemptPath, patch.evidence);
    if (createHash('sha256').update(diff).digest('hex') !== patch.sha256) {
      throw new Error('The saved change patch does not match its receipt.');
    }
    change = `<section><h2>Supplied change patch</h2>
<p>${escape(patch.source)} · SHA-256 <code>${escape(patch.sha256)}</code></p><pre>${escape(diff.toString('utf8'))}</pre></section>`;
  }
  return `<!doctype html>
<html lang="en"><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
<title>CareerPilot local acceptance</title>
<style>
body{font:16px/1.55 system-ui,sans-serif;background:#f6f8fa;color:#17202a;margin:2rem auto;padding:0 1rem;max-width:58rem}
h1,h2{line-height:1.2}h2{font-size:1.18rem}section{background:white;border:1px solid #d8dee4;border-radius:.5rem;margin:1rem 0;padding:0 1rem 1rem}
code{overflow-wrap:anywhere}pre{overflow:auto;padding:.75rem;background:#f6f8fa}summary{cursor:pointer}
</style>
<main><h1>CareerPilot local acceptance</h1>
<p>Status <strong>${escape(receipt.status)}</strong> · ${escape(receipt.attempt)}</p>
<p>Worktree <code>${escape(receipt.workspace ?? 'unavailable')}</code><br>
Checked commit <code>${escape(receipt.checked_commit ?? 'unavailable')}</code><br>
Inputs SHA-256 <code>${escape(receipt.dirty_inputs_fingerprint ?? 'unavailable')}</code></p>
${receipt.reason ? `<p>${escape(receipt.reason)}</p>` : ''}
${change}
${checks.join('\n')}
<section><h2>Coverage limits</h2><ul>${receipt.limitations.map((line) => `<li>${escape(line)}</li>`).join('')}</ul></section>
</main></html>\n`;
}

function request(url) {
  return new Promise((resolve, reject) => {
    const request = get(url, { agent: false }, (response) => {
      const chunks = [];
      response.on('data', (chunk) => chunks.push(chunk));
      response.on('error', reject);
      response.on('end', () => resolve({
        status: response.statusCode,
        content_type: response.headers['content-type'],
        csp: response.headers['content-security-policy'],
        body: Buffer.concat(chunks),
      }));
    });
    request.setTimeout(5000, () => request.destroy(new Error('Preview HTTP request timed out.')));
    request.on('error', reject);
  });
}

async function main() {
  const [runDir, port, mode] = process.argv.slice(2);
  const root = await realpath(runDir);
  const latest = await readEvidence(root, 'verify.json');
  const receipt = JSON.parse(latest);
  if (receipt.schema_version !== 1 || !/^attempt-[0-9TZ]+-[0-9a-f]{12}$/.test(receipt.attempt)) {
    throw new Error('Expected a verify.json generated by scripts/agent/verify.ps1.');
  }
  // The root receipt is the latest pointer. The attempt receipt is immutable.
  const attemptPath = basename(root) === receipt.attempt ? root : await realpath(join(root, receipt.attempt));
  if (attemptPath !== root && dirname(attemptPath) !== root) throw new Error('Attempt is outside the run directory.');
  const pinned = await readEvidence(attemptPath, 'verify.json');
  if (!latest.equals(pinned)) throw new Error('The latest acceptance receipt differs from its saved attempt.');
  const html = Buffer.from(await render(receipt, attemptPath));
  const sha256 = createHash('sha256').update(html).digest('hex');
  const previewPath = join(attemptPath, `preview-${randomUUID()}`);
  await mkdir(previewPath);
  await writeFile(join(previewPath, 'preview.html'), html);

  const headers = {
    'Cache-Control': 'no-store',
    'Content-Security-Policy': "default-src 'none'; style-src 'unsafe-inline'; frame-ancestors 'none'; base-uri 'none'",
    'Content-Type': 'text/html; charset=utf-8',
    'X-Content-Type-Options': 'nosniff',
  };
  const server = createServer((req, res) => {
    const address = server.address();
    if (req.headers.host !== `127.0.0.1:${address.port}`) {
      res.writeHead(403).end();
    } else if (req.url !== '/') {
      res.writeHead(404).end();
    } else if (!['GET', 'HEAD'].includes(req.method)) {
      res.writeHead(405, { Allow: 'GET, HEAD' }).end();
    } else {
      res.writeHead(200, { ...headers, 'Content-Length': html.length });
      res.end(req.method === 'GET' ? html : undefined);
    }
  });
  const evidence = {
    status: 'blocked',
    attempt: receipt.attempt,
    verify_status: receipt.status,
    verify_sha256: createHash('sha256').update(pinned).digest('hex'),
    html_sha256: sha256,
  };
  try {
    await new Promise((resolve, reject) => {
      server.once('error', reject);
      server.listen(Number(port), '127.0.0.1', resolve);
    });
    const { address, port: boundPort } = server.address();
    const url = `http://${address}:${boundPort}/`;
    evidence.url = url;
    const page = await request(url);
    const missing = await request(new URL('/verify.json', url));
    const bodyMatches = page.body.equals(html);
    evidence.http = {
      status: page.status, content_type: page.content_type, csp: page.csp,
      bytes: page.body.length, body_matches_preview_html: bodyMatches,
      body_sha256: createHash('sha256').update(page.body).digest('hex'),
      non_preview_path_status: missing.status,
    };
    await writeFile(join(previewPath, 'http-body.html'), page.body);
    evidence.status = page.status === 200 && page.content_type === headers['Content-Type'] &&
      page.csp === headers['Content-Security-Policy'] && bodyMatches && missing.status === 404 ? 'passed' : 'failed';
  } catch (error) {
    evidence.reason = error.message;
  } finally {
    await writeFile(join(previewPath, 'preview.json'), JSON.stringify(evidence, null, 2) + '\n');
    console.log(`${evidence.status}: ${join(previewPath, 'preview.json')}`);
    if (evidence.status !== 'passed' || mode === '--check') server.close();
  }
  if (evidence.status === 'passed' && mode !== '--check') {
    console.log(`${evidence.url} (Ctrl+C to stop)`);
  }
  return { passed: 0, failed: 1, blocked: 2 }[evidence.status];
}

try {
  process.exitCode = await main();
} catch (error) {
  console.error(`Preview blocked: ${error.message}`);
  process.exitCode = 2;
}
