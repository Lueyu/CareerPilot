export const toolCopyKeys = Object.keys(zh);

export type ToolCopy = (key: string, values?: Readonly<Record<string, string | number>>) => string;

function makeCopy(locale: Locale): ToolCopy {
  const dict = locale === "en" ? en : zh;
  return (key, values) => {
    const text = dict[key] ?? zh[key];
    if (typeof text !== "string") throw new Error(`Unknown tool copy key: ${key}`);
    return text.replace(/\{(\w+)\}/g, (match, name: string) =>
      values && Object.prototype.hasOwnProperty.call(values, name) ? String(values[name]) : match,
    );
  };
}

export function toolCopy(locale: Locale): ToolCopy {
  return makeCopy(locale);
}

export function useToolCopy(): ToolCopy {
  return makeCopy(useLocale());
}

export function toolReply(intent: ToolIntent, locale: Locale): string {
  return makeCopy(locale)(`reply.${intent}`);
}
