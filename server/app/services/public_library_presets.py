def preset_directions(role: str) -> list[dict[str, str]]:
    pairs = next(
        (directions for terms, directions in PRESETS if any(term in role.casefold() for term in terms)),
        (
            ("岗位任务", f"如果你以「{role}」入职，如何确认第一个月最重要的一项交付，怎样向负责人证明它达标？"),
            ("现场判断", f"以「{role}」的一项常见工作为例。若时间突然减半，你会如何决定保留、调整或推迟哪些工作？"),
            ("成果复盘", f"请选一项能体现「{role}」能力的经历，说明你本人的判断、交付结果和下一次要改的地方。"),
        ),
    )
    return [{"name": name, "example": example, "origin": "preset"} for name, example in pairs]
